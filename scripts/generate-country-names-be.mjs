#!/usr/bin/env node
/**
 * Builds `shared/country-names-be.ts`: Belarusian country names for every code in `shared/countries.ts`.
 *
 * Browsers ship no Belarusian region data (`Intl.DisplayNames(['be'], { type: 'region' })` answers in English), so the
 * names are taken once from Node's ICU (CLDR) and committed. The script is run by hand, never in CI or at build time.
 *
 * The names depend on the CLDR version inside Node, so the file is not byte-identical across Node versions. The header
 * records the Node, ICU and CLDR versions used (no timestamp): two runs with the same Node give identical bytes.
 * The country codes are read from `shared/countries.ts` as text, because Node 22.12 cannot import `.ts` files.
 *
 * Usage:
 *   node scripts/generate-country-names-be.mjs
 *   node scripts/generate-country-names-be.mjs --output /tmp/country-names-be.ts
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const COUNTRIES_PATH = fileURLToPath(new URL('../shared/countries.ts', import.meta.url));
const DEFAULT_OUTPUT = fileURLToPath(new URL('../shared/country-names-be.ts', import.meta.url));

function parseArgs(argv) {
  const options = { output: DEFAULT_OUTPUT, help: false };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--help' || arg === '-h') {
      options.help = true;
      continue;
    }
    const [flag, inlineValue] = arg.includes('=') ? arg.split('=', 2) : [arg, undefined];
    if (flag !== '--output') throw new Error(`Unknown argument: ${arg}`);
    if (inlineValue !== undefined) {
      options.output = resolve(inlineValue);
    } else {
      index += 1;
      const value = argv[index];
      if (value === undefined) throw new Error(`Missing value for ${flag}`);
      options.output = resolve(value);
    }
  }
  return options;
}

function printHelp() {
  console.log(`Build shared/country-names-be.ts from Node's ICU (CLDR).

Options:
  --output <file>   write here (default: shared/country-names-be.ts)
  --help            show this message`);
}

/** The codes of `countryCodes`, in the order they are listed in the source text. */
function readCountryCodes(source) {
  const block = source.match(/export const countryCodes = \[([\s\S]*?)\] as const;/);
  if (!block) throw new Error('Could not find `countryCodes` in shared/countries.ts');
  const codes = [...block[1].matchAll(/'([A-Z]{2})'/g)].map((match) => match[1]);
  if (codes.length === 0) throw new Error('`countryCodes` in shared/countries.ts is empty');
  return codes;
}

function buildNames(codes) {
  const displayNames = new Intl.DisplayNames(['be'], { type: 'region' });
  return codes.map((code) => {
    const name = displayNames.of(code);
    if (!name || name === code || !/\p{Script=Cyrillic}/u.test(name)) {
      throw new Error(`No Belarusian name for ${code} (ICU answered "${name}"); is Node built with full ICU?`);
    }
    return [code, name];
  });
}

function render(entries) {
  const { node, icu, cldr } = process.versions;
  const lines = [
    '/**',
    ' * Generated by `node scripts/generate-country-names-be.mjs`; do not edit by hand.',
    ' *',
    ` * Source: Node ${node}, ICU ${icu}, CLDR ${cldr} (\`Intl.DisplayNames\`, locale "be", type "region").`,
    ' * Browsers have no Belarusian region data, so the names are kept here. Entries follow `countryCodes`.',
    ' * A draft until a native speaker has read it, like the other Belarusian texts.',
    ' */',
    'export const countryNamesBe: Readonly<Record<string, string>> = {',
    ...entries.map(([code, name]) => `  ${code}: ${JSON.stringify(name)},`),
    '};',
    '',
  ];
  return lines.join('\n');
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  if (options.help) {
    printHelp();
    return;
  }

  const codes = readCountryCodes(await readFile(COUNTRIES_PATH, 'utf8'));
  const entries = buildNames(codes);
  await mkdir(dirname(options.output), { recursive: true });
  await writeFile(options.output, render(entries), 'utf8');
  console.error(`wrote ${entries.length} names to ${options.output}`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
