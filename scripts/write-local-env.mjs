#!/usr/bin/env node
/**
 * Writes .env.local for local Supabase (Docker) + Turnstile always-pass keys.
 * Run after: npx supabase start
 *
 * Usage: node scripts/write-local-env.mjs
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const FIXED_LOCAL = {
  VITE_TURNSTILE_SITE_KEY: '1x00000000000000000000AA',
  TURNSTILE_SECRET_KEY: '1x0000000000000000000000000000000AA',
  RECOVERY_HMAC_SECRET: 'local-dev-recovery-hmac-secret-0001',
  SESSION_HMAC_SECRET: 'local-dev-session-hmac-secret-00001',
  IP_HASH_SALT: 'local-dev-ip-hash-salt-000000000001',
  SESSION_COOKIE_NAME: 'anonymous_session',
  SESSION_MAX_AGE_DAYS: '180',
  APP_PUBLIC_URL: 'http://localhost:3000',
};

const DEMO_RECOVERY = 'AQEBAQEBAQEBAQEBAQEBAQEBAQEBAQEBAQEBAQEBAQE';

function parseStatusEnv(raw) {
  const values = {};
  for (const line of raw.split(/\r?\n/)) {
    const match = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (!match) continue;
    let value = match[2].trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    values[match[1]] = value;
  }
  return values;
}

function readSupabaseStatusEnv() {
  try {
    return parseStatusEnv(
      execFileSync('npx', ['supabase', 'status', '-o', 'env'], {
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'pipe'],
      }),
    );
  } catch (error) {
    const stderr = error instanceof Error && 'stderr' in error ? String(error.stderr ?? '') : '';
    console.error('Could not read local Supabase status. Start it first:\n  npx supabase start\n');
    if (stderr.trim()) console.error(stderr.trim());
    process.exit(1);
  }
}

const status = readSupabaseStatusEnv();
const apiUrl = status.API_URL ?? status.SUPABASE_URL;
const serviceRoleKey =
  status.SERVICE_ROLE_KEY ??
  status.SUPABASE_SERVICE_ROLE_KEY ??
  status.SECRET_KEY ??
  status.SUPABASE_SECRET_KEY;
const databaseUrl = status.DB_URL ?? status.DATABASE_URL ?? status.POSTGRES_URL;

if (!apiUrl || !serviceRoleKey) {
  console.error(
    'Supabase status did not include API_URL and a secret key (SERVICE_ROLE_KEY or SECRET_KEY).',
  );
  console.error('Keys found:', Object.keys(status).sort().join(', ') || '(none)');
  process.exit(1);
}

const lines = [
  '# Generated by scripts/write-local-env.mjs — do not commit.',
  '# Browser-visible. This is the only variable intentionally included in the Vite bundle.',
  `VITE_TURNSTILE_SITE_KEY=${FIXED_LOCAL.VITE_TURNSTILE_SITE_KEY}`,
  '',
  '# Server-only Vercel Function configuration.',
  `TURNSTILE_SECRET_KEY=${FIXED_LOCAL.TURNSTILE_SECRET_KEY}`,
  `SUPABASE_URL=${apiUrl}`,
  `SUPABASE_SERVICE_ROLE_KEY=${serviceRoleKey}`,
  `RECOVERY_HMAC_SECRET=${FIXED_LOCAL.RECOVERY_HMAC_SECRET}`,
  `SESSION_HMAC_SECRET=${FIXED_LOCAL.SESSION_HMAC_SECRET}`,
  `IP_HASH_SALT=${FIXED_LOCAL.IP_HASH_SALT}`,
  `SESSION_COOKIE_NAME=${FIXED_LOCAL.SESSION_COOKIE_NAME}`,
  `SESSION_MAX_AGE_DAYS=${FIXED_LOCAL.SESSION_MAX_AGE_DAYS}`,
  `APP_PUBLIC_URL=${FIXED_LOCAL.APP_PUBLIC_URL}`,
  '',
  '# Test-only connection to the local Supabase Postgres instance.',
  `DATABASE_URL=${databaseUrl ?? ''}`,
  '',
];

const outPath = resolve(process.cwd(), '.env.local');
writeFileSync(outPath, `${lines.join('\n')}\n`, 'utf8');

console.log(`Wrote ${outPath}`);
console.log('');
console.log('Demo UI restore:');
console.log(`  ${FIXED_LOCAL.APP_PUBLIC_URL}/#restore=${DEMO_RECOVERY}`);
console.log('');
console.log('Next:');
console.log('  npm run local:dev');
