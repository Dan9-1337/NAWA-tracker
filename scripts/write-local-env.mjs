#!/usr/bin/env node
/**
 * Writes .env.local for local Supabase (Docker) + signed Telegram dev initData.
 * Run after: npx supabase start
 *
 * Usage: node scripts/write-local-env.mjs
 */
import { createHmac } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const FIXED_LOCAL = {
  TELEGRAM_BOT_TOKEN: 'local-dev-telegram-bot-token-0000000001',
  IP_HASH_SALT: 'local-dev-ip-hash-salt-000000000001',
  APP_PUBLIC_URL: 'http://localhost:3000',
};

const DEMO_TELEGRAM_USER_ID = 900000001;

function signTelegramInitData(userId, username, botToken) {
  const authDate = Math.floor(Date.now() / 1000);
  const params = new URLSearchParams({
    user: JSON.stringify({ id: userId, username }),
    auth_date: String(authDate),
  });
  const dataCheckString = [...params.entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([key, value]) => `${key}=${value}`)
    .join('\n');
  const secretKey = createHmac('sha256', botToken).update('WebAppData').digest();
  const hash = createHmac('sha256', secretKey).update(dataCheckString).digest('hex');
  params.set('hash', hash);
  return params.toString();
}

function parseStatusEnv(raw) {
  const values = {};
  for (const line of raw.split(/\r?\n/)) {
    const match = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (!match) continue;
    let value = match[2].trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    values[match[1]] = value;
  }
  return values;
}

function readSupabaseStatusEnv() {
  try {
    return parseStatusEnv(
      execFileSync('npx', ['supabase', 'status', '-o', 'env'], {
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'pipe'],
      }),
    );
  } catch (error) {
    const stderr = error instanceof Error && 'stderr' in error ? String(error.stderr ?? '') : '';
    console.error('Could not read local Supabase status. Start it first:\n  npx supabase start\n');
    if (stderr.trim()) console.error(stderr.trim());
    process.exit(1);
  }
}

const status = readSupabaseStatusEnv();
const apiUrl = status.API_URL ?? status.SUPABASE_URL;
const serviceRoleKey =
  status.SERVICE_ROLE_KEY ??
  status.SUPABASE_SERVICE_ROLE_KEY ??
  status.SECRET_KEY ??
  status.SUPABASE_SECRET_KEY;
const databaseUrl = status.DB_URL ?? status.DATABASE_URL ?? status.POSTGRES_URL;

if (!apiUrl || !serviceRoleKey) {
  console.error(
    'Supabase status did not include API_URL and a secret key (SERVICE_ROLE_KEY or SECRET_KEY).',
  );
  console.error('Keys found:', Object.keys(status).sort().join(', ') || '(none)');
  process.exit(1);
}

const devInitData = signTelegramInitData(DEMO_TELEGRAM_USER_ID, 'demo_applicant', FIXED_LOCAL.TELEGRAM_BOT_TOKEN);

const lines = [
  '# Generated by scripts/write-local-env.mjs — do not commit.',
  '# Browser-visible dev initData for local testing outside Telegram WebView.',
  `VITE_TELEGRAM_DEV_INIT_DATA=${devInitData}`,
  '',
  '# Server-only Vercel Function configuration.',
  `TELEGRAM_BOT_TOKEN=${FIXED_LOCAL.TELEGRAM_BOT_TOKEN}`,
  `SUPABASE_URL=${apiUrl}`,
  `SUPABASE_SERVICE_ROLE_KEY=${serviceRoleKey}`,
  `IP_HASH_SALT=${FIXED_LOCAL.IP_HASH_SALT}`,
  `APP_PUBLIC_URL=${FIXED_LOCAL.APP_PUBLIC_URL}`,
  '',
  '# Test-only connection to the local Supabase Postgres instance.',
  `DATABASE_URL=${databaseUrl ?? ''}`,
  '',
];

const outPath = resolve(process.cwd(), '.env.local');
writeFileSync(outPath, `${lines.join('\n')}\n`, 'utf8');

console.log(`Wrote ${outPath}`);
console.log('');
console.log(`Demo Telegram user id: ${DEMO_TELEGRAM_USER_ID} (seeded profile in supabase/seed.sql)`);
console.log('');
console.log('Next:');
console.log('  npm run local:dev');
